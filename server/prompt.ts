// 답변 생성 프롬프트.
//
// 원래 gemini.ts 안에 있었는데, 생성기가 둘(Gemini·Ollama)이 되면서 뺐다.
// 프롬프트는 "무엇을 근거로 어떻게 답하라"는 정책이라 벤더와 무관해야 하고,
// 벤더 파일마다 복사해두면 규칙을 한쪽만 고치는 버그가 생긴다 — 인용 형식을
// 바꿨는데 로컬 모델로 폴백한 답변만 옛 형식으로 나오는 식이다.
//
// rag/(코어)에 넣지 않은 이유: 프롬프트 문구는 모델을 향한 말이라 모델 계층의
// 것이다. 코어는 "발췌를 근거로 답을 만들라"고 시키는 쪽이지, 그걸 어떤 문장으로
// 모델에게 전달할지는 어댑터가 정한다.

import type { RetrievedChunk } from "./types.ts";

export function buildAnswerPrompt(
  question: string,
  contexts: RetrievedChunk[],
  hasImage: boolean
): string {
  const contextBlock = contexts
    .map((c, i) => `[${i + 1}] (출처: ${c.filename})\n${c.content}`)
    .join("\n\n");

  // 근거가 무엇인지(발췌·이미지·둘 다)에 따라 지시가 달라진다.
  // 발췌가 하나도 없는 호출은 엔진이 "문서에서는 못 찾았지만 이미지가 있어
  // 거절하지 않은" 경우뿐이다(rag/engine.ts [3]). 그때 발췌용 지시를 그대로
  // 쓰면 빈 발췌를 근거로 "문서에 없다"고만 답하므로, 근거를 이미지로 바꾼다.
  let intro: string;
  let grounding: string;
  if (hasImage && contexts.length > 0) {
    intro = "당신은 사용자가 업로드한 문서와 첨부한 이미지를 근거로 답하는 어시스턴트입니다.";
    grounding =
      "- 아래 발췌 내용과 첨부된 이미지만 근거로 답합니다. 둘 다에 없는 내용은 추측하지 말고 없다고 답하세요.\n" +
      "- 근거로 사용한 발췌 번호를 문장 끝에 [1], [2] 형태로 표시하세요. 이미지에서 읽은 내용에는 번호를 붙이지 않습니다.";
  } else if (hasImage) {
    intro = "당신은 사용자가 첨부한 이미지를 보고 답하는 어시스턴트입니다.";
    grounding =
      "- 첨부된 이미지에서 확인할 수 있는 내용만 근거로 답합니다. 이미지에서 확인할 수 없는 내용은 추측하지 말고 확인할 수 없다고 답하세요.";
  } else {
    intro = "당신은 사용자가 업로드한 문서를 근거로 답하는 어시스턴트입니다.";
    grounding =
      "- 아래 발췌 내용만 근거로 답합니다. 발췌에 없는 내용은 추측하지 말고 문서에 없다고 답하세요.\n" +
      "- 근거로 사용한 발췌 번호를 문장 끝에 [1], [2] 형태로 표시하세요.";
  }

  return `${intro}

규칙:
${grounding}
- 한국어로 간결하게 답하세요.
- 굵게(**), 제목(#), 별표 목록(*) 같은 마크다운 서식은 쓰지 마세요.
  평범한 문장으로 답하고, 항목을 나열할 땐 줄바꿈만 쓰세요.

${contexts.length > 0 ? `발췌:\n${contextBlock}\n\n` : ""}질문: ${question}`;
}
