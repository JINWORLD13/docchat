// 채팅의 신원.
//
// 왜 필요했나: 파괴적인 동작(방 삭제·보낸 것 취소)의 권한을 닉네임으로
// 판단하고 있었다. 그런데 닉네임은 접속자 목록과 말풍선으로 방 전체에 공개되고,
// hello는 언제든 다시 보낼 수 있다. 즉 남의 닉네임을 그대로 적어 보내면
// 그 사람의 방을 지우고 그 사람의 메시지를 취소할 수 있었다.
// 취소가 이미지였다면 DB에 있는 바이트까지 지워진다 — 되돌릴 수 없다.
//
// 로그인을 붙이는 게 정답이지만, 그전에도 "표시용 이름"과 "권한의 근거"를
// 같은 값으로 쓰지 않을 수는 있다. 그래서 둘을 나눴다.
//
//   clientKey  브라우저가 만들어 localStorage에 보관하는 임의의 값. 서버로만
//              보내고 다른 사람에게는 절대 안 나간다. 재연결·새로고침해도
//              같으므로 "새로고침하면 내 방을 못 지운다" 문제가 없다.
//   authorId   clientKey를 서버 비밀키로 HMAC한 값. 이건 공개해도 된다 —
//              방 전체에 뿌려도 여기서 clientKey를 되돌릴 수 없다.
//
// 화면은 authorId로 "내 것"을 판단하고(취소 버튼 표시), 서버는 authorId로
// 권한을 확인한다. 남의 authorId를 봐도 자기 clientKey에서 그 값이 나오지
// 않으므로 흉내낼 수 없다.
//
// 한계는 분명하다. clientKey를 아는 사람(같은 브라우저를 쓰는 사람)은 그대로
// 그 신원이고, 브라우저를 지우면 신원도 사라진다. 계정이 아니라 "이 브라우저"
// 수준의 신원이라는 뜻이다. 그래도 닉네임을 적어 보내는 것보다는 훨씬 낫다.

import { createHmac, randomBytes, randomUUID } from "node:crypto";

// 프로세스마다 새로 만든다. 서버가 재시작하면 authorId도 전부 바뀌는데,
// 방과 대화 기록도 메모리라 같이 사라지므로 수명이 맞다.
// (영구 저장을 붙이는 단계가 오면 이 비밀키도 환경변수로 나가야 한다.)
const SECRET = randomBytes(32);

// clientKey를 공개해도 되는 id로 바꾼다.
// 16자면 충돌 확률이 무시할 수준이고(64비트), 로그와 페이로드가 짧아진다.
export function authorIdOf(clientKey: string): string {
  return createHmac("sha256", SECRET).update(clientKey).digest("hex").slice(0, 16);
}

// 클라이언트가 clientKey를 안 보냈을 때(직접 만든 클라이언트, 옛 버전) 쓸 값.
// 연결마다 새로 생기므로 재연결하면 신원이 바뀐다 — 즉 자기가 만든 방을 못
// 지우게 되지만, 그건 그 클라이언트의 사정이고 남의 것을 건드릴 수는 없다.
export function anonymousKey(): string {
  return randomUUID();
}

// clientKey는 우리가 검증할 수 있는 모양이 아니다(브라우저가 만든 값).
// 그래도 길이는 제한한다 — 이 값이 HMAC 입력으로 들어가므로, 제한이 없으면
// 거대한 문자열을 보내 연결마다 CPU를 태울 수 있다.
export const MAX_CLIENT_KEY = 100;
